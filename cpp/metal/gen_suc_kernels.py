"""Generate cpp/metal/suc_kernels.metal from the Python/MLX kernel sources (single source of truth).

The C++ runtime (cpp/src/metal_backend.cpp) compiles the generated file at run time (newLibraryWithSource; the
Command Line Tools ship no offline `metal` compiler) and instantiates the templates below with explicit
`template [[host_name(...)]]` lines, exactly as mx.fast.metal_kernel does for the Python kernels. The kernel BODIES
and helper headers are copied verbatim from

    suc.kernels.vq_matmul       _HEADER, _LOOKUP_SRC ("vec" path), _MMA_REG_SRC ("mma" path, MMA_KIND = "reg")
    suc.kernels.rotation        _HEADER (H_m tables, row + blocks layouts), the row-layout kernels (_kernel), the
                                element-wise prologues (_pro_blocks_kernel / _pro_kernel: RMSNorm + input rotation, K6)
    suc.runtime.compressed_model _STRUCT_HEADER, _STRUCT_SRC (column-structured + CSR residual)
    suc.kernels.suc_switch      _PROLOGUE (tile -> expert), _RESIDUAL_SRC (stacked CSR residual), _COLRES_SRC (stacked
                                column-structured residual + CSR tail), with the vq_matmul
                                bodies and rotation._blocks_kernel(row_signs=True) (MoE expert stacks)
    suc.kernels.tcq_matmul      _TCQ_HEADER, _SRC ("vec"), _MMA_SRC ("mma"), _SWITCH_PROLOGUE (trellis-coded tensors
                                and expert stacks)

so the numerics are those of the MLX kernels by construction; only the signatures (MLX generates them from
input_names / template lists) are written here, in MLX's style. tests/unit/test_cpp_metal.py checks that the
checked-in .metal equals the output of this script, so a change of a Python kernel fails until this file is
regenerated:

    .venv/bin/python cpp/metal/gen_suc_kernels.py            # rewrites cpp/metal/suc_kernels.metal
"""
from __future__ import annotations

import sys
from pathlib import Path

OUT = Path(__file__).with_name("suc_kernels.metal")

_POS = """    uint3 thread_position_in_grid [[thread_position_in_grid]],
    uint3 thread_position_in_threadgroup [[thread_position_in_threadgroup]],
    uint3 threadgroup_position_in_grid [[threadgroup_position_in_grid]],
    uint3 threads_per_threadgroup [[threads_per_threadgroup]],
    uint simdgroup_index_in_threadgroup [[simdgroup_index_in_threadgroup]],
    uint thread_index_in_simdgroup [[thread_index_in_simdgroup]])"""

_PRELUDE = """// GENERATED by cpp/metal/gen_suc_kernels.py from the Python/MLX kernels -- do not edit by hand.
// Kernel bodies and helpers are verbatim copies of suc.kernels.vq_matmul, suc.kernels.rotation and
// suc.runtime.compressed_model; the C++ host (cpp/src/metal_backend.cpp) instantiates the templates.
#include <metal_stdlib>
#include <metal_simdgroup>
#include <metal_simdgroup_matrix>
using namespace metal;
"""


def _section(title: str) -> str:
    return f"\n// {'=' * 100}\n// {title}\n// {'=' * 100}\n"


def _captured_source(factory, *args) -> str:
    """The `source` a kernel factory of the Python runtime passes to mx.fast.metal_kernel (bodies that are assembled
    per call, e.g. rotation._blocks_kernel per segment count), captured without compiling anything."""
    import mlx.core as mx

    seen = {}
    real = mx.fast.metal_kernel

    def capture(**kw):
        seen.update(kw)
        return None
    mx.fast.metal_kernel = capture
    try:
        getattr(factory, "__wrapped__", factory)(*args)
    finally:
        mx.fast.metal_kernel = real
    return seen["source"]


def _patched(sl, kind: str) -> str:
    """The body suc.kernels.suc_linear._fused_kernel(kind) compiles: the vq_matmul source with its segment patches."""
    get_src, subs = sl._PATCHES[kind]
    src = get_src()
    for old, new in subs:
        if src.count(old) != 1:
            raise RuntimeError(f"suc.kernels.vq_matmul {kind} source changed: cannot patch {old!r}")
        src = src.replace(old, new)
    return src


_TAB_DEF = """
#define SUC_SEG_START(s) ((s) == 0 ? 0u : (s) == 1 ? uint(SB1) : (s) == 2 ? uint(SB2) : uint(SB3))
#define SUC_TAB_PO(m, r) (tab[SUC_SEG(r) * (M + 1) + (m)] + ulong((r) - SUC_SEG_START(SUC_SEG(r))) * WORDS)
#define SUC_TAB_SO(r) (tab[SUC_SEG(r) * (M + 1) + M] + ulong((r) - SUC_SEG_START(SUC_SEG(r))))
"""
_TAB_SUBS = {
    "vec": [("packed + (m * OUT + rows[rr]) * WORDS", "packed + SUC_TAB_PO(m, rows[rr])"),
            ("float s = scales[rows[rr]];", "float s = scales[SUC_TAB_SO(rows[rr])];")],
    "mma": [("packed + (m * OUT + row) * WORDS", "packed + SUC_TAB_PO(m, row)"),
            ("float s = scales[r];", "float s = scales[SUC_TAB_SO(r)];")],
}


def _tabbed(src: str, kind: str) -> str:
    """The fused body with table addressing of the packed indices and row scales (see _TAB_DEF)."""
    for old, new in _TAB_SUBS[kind]:
        if src.count(old) != 1:
            raise RuntimeError(f"fused {kind} source changed: cannot patch {old!r} for the in-place variant")
        src = src.replace(old, new)
    return src


def generate() -> str:
    import suc.kernels.rotation as rot
    import suc.kernels.suc_linear as sl
    import suc.kernels.vq_matmul as vm
    import suc.runtime.compressed_model as cm

    parts = [_PRELUDE]
    parts += [_section("suc.kernels.vq_matmul._HEADER"), vm._HEADER]
    parts += [_section("suc.kernels.rotation._HEADER"), rot._HEADER]
    parts += [_section("suc.runtime.compressed_model._STRUCT_HEADER"), cm._STRUCT_HEADER]

    # ---- lookup "vec" path (template order = suc.kernels.vq_matmul._launch, vec branch) + TS (row-scale type:
    # the file stores f16 row scales; float(half) is exact, so reading them directly equals MLX's float32 copy)
    parts += [_section("suc_lookup_vec: suc.kernels.vq_matmul._LOOKUP_SRC"), """
template <typename T, int BT, int OUT, int IN, int NG, int G, int K, int BITS, int WORDS, int SG, int M, int R,
          int VEC, int CBTG, int HM, typename TO, typename TS>
[[kernel]] void suc_lookup_vec(
    const device T* x [[buffer(0)]],
    const device half* codebook [[buffer(1)]],
    const device uint32_t* packed [[buffer(2)]],
    const device TS* scales [[buffer(3)]],
    device TO* y [[buffer(4)]],
""" + _POS + " {\n" + vm._LOOKUP_SRC + "}\n"]

    # ---- simdgroup-matrix "mma" path, register-fragment variant
    parts += [_section("suc_lookup_mma: suc.kernels.vq_matmul._MMA_REG_SRC"), """
template <typename T, int BT, int OUT, int IN, int NG, int G, int K, int BITS, int WORDS, int SG, int M, int RT,
          int NB, int KCG, typename TT, int CBTG, typename TO, typename TS>
[[kernel]] void suc_lookup_mma(
    const device T* x [[buffer(0)]],
    const device half* codebook [[buffer(1)]],
    const device uint32_t* packed [[buffer(2)]],
    const device TS* scales [[buffer(3)]],
    device TO* y [[buffer(4)]],
""" + _POS + " {\n" + vm._MMA_REG_SRC + "}\n"]

    # ---- fused (row-concatenated) projections: the same bodies with suc.kernels.suc_linear's segment patches
    # (SUC_SEG(r): codebook set of output row r; SB1..SB3 = segment boundaries, unused ones = OUT)
    parts += [_section("suc_fused_lookup_vec / _mma: suc.kernels.suc_linear._PATCHES (fused_matmul_metal)"),
              sl._SEG_DEF]
    parts += ["""
template <typename T, int BT, int OUT, int IN, int NG, int G, int K, int BITS, int WORDS, int SB1, int SB2, int SB3,
          int SG, int M, int R, int VEC, int CBTG, int HM, typename TO, typename TS>
[[kernel]] void suc_fused_lookup_vec(
    const device T* x [[buffer(0)]],
    const device half* codebook [[buffer(1)]],
    const device uint32_t* packed [[buffer(2)]],
    const device TS* scales [[buffer(3)]],
    device TO* y [[buffer(4)]],
""" + _POS + " {\n" + _patched(sl, "vec") + "}\n"]
    parts += ["""
template <typename T, int BT, int OUT, int IN, int NG, int G, int K, int BITS, int WORDS, int SB1, int SB2, int SB3,
          int SG, int M, int RT, int NB, int KCG, typename TT, int CBTG, typename TO, typename TS>
[[kernel]] void suc_fused_lookup_mma(
    const device T* x [[buffer(0)]],
    const device half* codebook [[buffer(1)]],
    const device uint32_t* packed [[buffer(2)]],
    const device TS* scales [[buffer(3)]],
    device TO* y [[buffer(4)]],
""" + _POS + " {\n" + _patched(sl, "mma") + "}\n"]

    # ---- C++-only in-place variants of the fused kernels: each member's packed indices and f16 row scales are read
    # where they lie in the mapped file, through a per-(segment, index stream) offset table (tab[s * (M + 1) + m] =
    # element offset of stream m of segment s, tab[s * (M + 1) + M] = its row scales). Only the row addressing of
    # the bodies above is replaced; the arithmetic (and so every output bit) is that of the verbatim kernels.
    parts += [_section("suc_fused_lookup_vec_tab / _mma_tab: fused kernels reading the members in place (C++ only)"),
              _TAB_DEF]
    for kind, tmpl in (("vec", "int SG, int M, int R, int VEC, int CBTG, int HM, typename TO, typename TS"),
                       ("mma", "int SG, int M, int RT, int NB, int KCG, typename TT, int CBTG, typename TO, typename TS")):
        parts += [f"""
template <typename T, int BT, int OUT, int IN, int NG, int G, int K, int BITS, int WORDS, int SB1, int SB2, int SB3,
          {tmpl}>
[[kernel]] void suc_fused_lookup_{kind}_tab(
    const device T* x [[buffer(0)]],
    const device half* codebook [[buffer(1)]],
    const device uint32_t* packed [[buffer(2)]],
    const device TS* scales [[buffer(3)]],
    device TO* y [[buffer(4)]],
    const device ulong* tab [[buffer(5)]],
""" + _POS + " {\n" + _tabbed(_patched(sl, kind), kind) + "}\n"]

    # ---- rotation, "blocks" layout, one segment (the body suc.kernels.rotation._blocks_kernel(1, False) builds)
    parts += [_section("suc_rot_blocks: suc.kernels.rotation._blocks_kernel(nseg=1, split=False)"), """
template <typename TX, typename TY, int Q, int T, int C, int INV, int NTOT, int BUFQ, int M0, int P0, int OFF0,
          int GS0, int GE0>
[[kernel]] void suc_rot_blocks(
    const device TX* x [[buffer(0)]],
    const device float* signs [[buffer(1)]],
    device TY* y [[buffer(2)]],
""" + _POS + " {\n" + _captured_source(rot._blocks_kernel, 1, False) + "\n}\n"]

    # ---- multi-segment rotations of fused projections (rht_inverse_fused(y, signs, sizes, split=...)): S = 2, 3
    # segments, one output (B, NTOT) or one output per segment (split)
    for nseg in (2, 3):
        seg_t = ", ".join(f"int M{s}, int P{s}, int OFF{s}, int GS{s}, int GE{s}" for s in range(nseg))
        for split in (False, True):
            name = f"suc_rot_blocks{nseg}{'_split' if split else ''}"
            outs = "".join(f"    device TY* y{s} [[buffer({2 + s})]],\n" for s in range(nseg)) if split else \
                "    device TY* y [[buffer(2)]],\n"
            parts += [_section(f"{name}: suc.kernels.rotation._blocks_kernel(nseg={nseg}, split={split})"), f"""
template <typename TX, typename TY, int Q, int T, int C, int INV, int NTOT, int BUFQ, {seg_t}>
[[kernel]] void {name}(
    const device TX* x [[buffer(0)]],
    const device float* signs [[buffer(1)]],
{outs}""" + _POS + " {\n" + _captured_source(rot._blocks_kernel, nseg, split) + "\n}\n"]

    # ---- RMSNorm + input rotation in one launch (K6 prologue, blocks layout; the body suc.kernels.rotation.
    # _pro_blocks_kernel(outn=True) passes, template order = rotation._prologue). PRO = 1: xn = rms_norm(x, w, eps)
    # (bit-identical to mx.fast.rms_norm for N <= 4096), y = H (σ ⊙ xn); xn is written too (residuals read it).
    parts += [_section("suc_rot_prologue_blocks: suc.kernels.rotation._pro_blocks_kernel(outn=True)"), """
template <int T, int Q, int C, int BUFN, int M, int P, int PRO, typename TX>
[[kernel]] void suc_rot_prologue_blocks(
    const device TX* x [[buffer(0)]],
    const device TX* w [[buffer(1)]],
    const device float* signs [[buffer(2)]],
    const device float* eps [[buffer(3)]],
    device TX* y [[buffer(4)]],
    device TX* xn [[buffer(5)]],
""" + _POS + " {\n" + _captured_source(rot._pro_blocks_kernel, True) + "\n}\n"]

    # ---- rotation, "row" layout (rotation._kernel / _plan: one threadgroup per row and segment, the K4 kernel; a
    # tuning cache selects it per size, e.g. n = 1024 on the M1 Ultra). hm: the H_m tables (unused with HC = 1).
    # Buffers: x, signs, hm, then sidx (row_signs) and the output(s).
    for nseg, split, rows in ((1, False, False), (1, False, True), (2, False, False), (2, True, False),
                              (3, False, False), (3, True, False)):
        seg_t = ", ".join(f"int M{s}, int P{s}, int C{s}, int OFF{s}, int HO{s}" for s in range(nseg))
        name = "suc_rot_row" + (str(nseg) if nseg > 1 else "") + ("_split" if split else "") + ("_rows" if rows else "")
        o = 3 + int(rows)
        outs = "".join(f"    device TY* y{s} [[buffer({o + s})]],\n" for s in range(nseg)) if split else \
            f"    device TY* y [[buffer({o})]],\n"
        sidx = "    const device uint32_t* sidx [[buffer(3)]],\n" if rows else ""
        parts += [_section(f"{name}: suc.kernels.rotation._kernel(nseg={nseg}, split={split}, row_signs={rows})"), f"""
template <typename TX, typename TY, int T, int INV, int BUFN, int HC, int NTOT, {seg_t}>
[[kernel]] void {name}(
    const device TX* x [[buffer(0)]],
    const device float* signs [[buffer(1)]],
    const device float* hm [[buffer(2)]],
{sidx}{outs}""" + _POS + " {\n" + _captured_source(rot._kernel, nseg, split, rows) + "\n}\n"]

    # ---- RMSNorm / SwiGLU + input rotation in one launch, "row" layout (rotation._pro_kernel(outn=True); template
    # order = rotation._prologue's row branch)
    parts += [_section("suc_rot_prologue_row: suc.kernels.rotation._pro_kernel(outn=True)"), """
template <int T, int BUFN, int HC, int M, int P, int C, int PRO, typename TX>
[[kernel]] void suc_rot_prologue_row(
    const device TX* x [[buffer(0)]],
    const device TX* w [[buffer(1)]],
    const device float* signs [[buffer(2)]],
    const device float* hm [[buffer(3)]],
    const device float* eps [[buffer(4)]],
    device TX* y [[buffer(5)]],
    device TX* xn [[buffer(6)]],
""" + _POS + " {\n" + _captured_source(rot._pro_kernel, True) + "\n}\n"]

    # ---- rotation fallback for sizes the blocks layout does not take (2^k < 32): dense O(n^2) per element.
    # Not an MLX kernel (Python falls back to mx.hadamard_transform there): float32, sequential sum over j.
    parts += [_section("suc_rot_dense: fallback for n = m * 2^k with 2^k < 32 (C++ only)"), """
// y[b, i] = s(i) * sum_j Hm[a_i, a_j] * (-1)^popcount(c_i & c_j) * s'(j) * x[b, j] / sqrt(P)   (i = a_i * P + c_i)
// forward (INV = 0): s' = signs, s = 1; inverse (INV = 1): Hm transposed, s' = 1, s = signs. hm: (M, M) float32.
template <typename TX, typename TY, int M, int P, int INV>
[[kernel]] void suc_rot_dense(
    const device TX* x [[buffer(0)]],
    const device float* signs [[buffer(1)]],
    device TY* y [[buffer(2)]],
    const device float* hm [[buffer(3)]],
""" + _POS + """ {
    constexpr uint N = M * P;
    uint i = thread_position_in_grid.x;
    uint b = thread_position_in_grid.y;
    if (i >= N) return;
    uint ai = i / P, ci = i % P;
    float acc = 0.0f;
    for (uint j = 0; j < N; ++j) {
        uint aj = j / P, cj = j % P;
        float coef = (popcount(ci & cj) & 1) ? -1.0f : 1.0f;
        coef *= INV ? hm[aj * M + ai] : hm[ai * M + aj];
        float v = float(x[b * N + j]);
        if (!INV) v *= signs[j];
        acc += coef * v;
    }
    float o = acc * rsqrt(float(P));
    if (INV) o *= signs[i];
    y[b * N + i] = static_cast<TY>(o);
}
"""]

    # ---- column-structured + CSR residual (template order = structured_residual_metal + the input dtypes MLX
    # derives from the arrays: x, ccols, cval, rcols, rvals)
    parts += [_section("suc_structured_residual: suc.runtime.compressed_model._STRUCT_SRC"), """
template <typename TXX, typename TCC, typename TCV, typename TRC, typename TRV, int IN, int OUT, int S, int CTOT,
          int BT, int XG, int RQ, int JS, int RED, bool HAS_COLS, bool HAS_CSR, typename OT>
[[kernel]] void suc_structured_residual(
    const device TXX* x [[buffer(0)]],
    const device float* y_in [[buffer(1)]],
    const device uint32_t* meta [[buffer(2)]],
    const device TCC* ccols [[buffer(3)]],
    const device TCV* cval [[buffer(4)]],
    const device float* cscale [[buffer(5)]],
    const device uint32_t* row_ptr [[buffer(6)]],
    const device TRC* rcols [[buffer(7)]],
    const device TRV* rvals [[buffer(8)]],
    const device float* rscale [[buffer(9)]],
    device OT* y [[buffer(10)]],
    const constant int* x_shape [[buffer(11)]],
""" + _POS + " {\n" + cm._STRUCT_SRC + "}\n"]
    parts += _switch_sections()
    parts += _tcq_sections()
    src = "".join(parts)
    if ')SUCMSL"' in src:
        raise RuntimeError("the raw-string delimiter )SUCMSL\" appears in the kernel source")
    return src


# Offset-table prologue (C++ only): the same tile -> expert mapping as suc.kernels.suc_switch._PROLOGUE, but the
# expert's codebooks / packed indices / row scales are found through a per-expert offset table eoff (E, 3) ulong
# (elements of codebook, packed, scales relative to the bound base pointers) instead of a dense (E, ...) stack, so the
# per-expert arrays can be read in place from the SUC1 mapping, where the experts are separate tensors. Only the
# pointer arithmetic differs; the kernel bodies (and so the numerics) are the same verbatim vq_matmul sources.
# An expert slot whose packed offset is ~0 is empty (a sub-stack of a mixed-codec stack addressed by global expert ids,
# cpp/src/metal/expert_mixed.cpp): the whole threadgroup (one routed row) returns before reading anything, so rows routed
# to experts of other codecs cost no weight reads; their (undefined) outputs are never selected.
_TAB_PROLOGUE = """
    {
        uint suc_t = threadgroup_position_in_grid.y;
        ulong suc_e = ulong(eidx[suc_t]);
        if (eoff[3 * suc_e + 1] == ~0ul) return;
        codebook += CBE ? eoff[3 * suc_e] : 0ul;
        packed += eoff[3 * suc_e + 1];
        scales += eoff[3 * suc_e + 2];
        x += ulong(suc_t) * ulong(BT * IN);
        y += ulong(suc_t) * ulong(BT * OUT);
    }
"""


def _switch_sections() -> list[str]:
    """MoE expert-stack kernels (suc.kernels.suc_switch): the lookup bodies behind the tile -> expert prologue
    (template CBE: 0 = one codebook set for all experts, 1 = per expert), the per-row-sign rotation, the stacked
    CSR residual and the stacked column-structured residual."""
    import suc.kernels.rotation as rot
    import suc.kernels.suc_switch as sw
    import suc.kernels.vq_matmul as vm

    parts = []
    vec_t = ("template <typename T, int BT, int OUT, int IN, int NG, int G, int K, int BITS, int WORDS, int CBE, int SG,"
             " int M, int R,\n          int VEC, int CBTG, int HM, typename TO, typename TS>\n")
    mma_t = ("template <typename T, int BT, int OUT, int IN, int NG, int G, int K, int BITS, int WORDS, int CBE, int SG,"
             " int M, int RT,\n          int NB, int KCG, typename TT, int CBTG, typename TO, typename TS>\n")
    args = """    const device T* x [[buffer(0)]],
    const device half* codebook [[buffer(1)]],
    const device uint32_t* packed [[buffer(2)]],
    const device TS* scales [[buffer(3)]],
    const device uint32_t* eidx [[buffer(4)]],
    device TO* y [[buffer(5)]],
"""
    tab = "    const device ulong* eoff [[buffer(6)]],\n"
    for kind, tmpl, body in (("vec", vec_t, vm._LOOKUP_SRC), ("mma", mma_t, vm._MMA_REG_SRC)):
        parts += [_section(f"suc_switch_lookup_{kind}: suc.kernels.suc_switch._PROLOGUE + vq_matmul "
                           f"{'_LOOKUP_SRC' if kind == 'vec' else '_MMA_REG_SRC'} (gather_matmul_metal)"),
                  tmpl + f"[[kernel]] void suc_switch_lookup_{kind}(\n" + args + _POS + " {\n" + sw._PROLOGUE + body
                  + "}\n"]
        parts += [_section(f"suc_switch_lookup_{kind}_tab: offset-table prologue (C++ only) + the same body"),
                  tmpl + f"[[kernel]] void suc_switch_lookup_{kind}_tab(\n" + args + tab + _POS + " {\n" + _TAB_PROLOGUE
                  + body + "}\n"]

    # ---- per-row sign table rotation (rotate(x, signs (E, n), rows=eidx)): row b uses signs + sidx[b] * NTOT
    parts += [_section("suc_rot_blocks_rows: suc.kernels.rotation._blocks_kernel(nseg=1, split=False, "
                       "row_signs=True)"), """
template <typename TX, typename TY, int Q, int T, int C, int INV, int NTOT, int BUFQ, int M0, int P0, int OFF0,
          int GS0, int GE0>
[[kernel]] void suc_rot_blocks_rows(
    const device TX* x [[buffer(0)]],
    const device float* signs [[buffer(1)]],
    const device uint32_t* sidx [[buffer(2)]],
    device TY* y [[buffer(3)]],
""" + _POS + " {\n" + _captured_source(rot._blocks_kernel, 1, False, True) + "\n}\n"]

    # ---- stacked CSR residual (gather_residual_metal): y = y_in + scale[e] · R_e x, rows e·OUT + r of the CSR
    parts += [_section("suc_switch_residual: suc.kernels.suc_switch._RESIDUAL_SRC (gather_residual_metal)"), """
template <typename TX, typename TC, typename TV, int IN, int OUT>
[[kernel]] void suc_switch_residual(
    const device TX* x [[buffer(0)]],
    const device float* y_in [[buffer(1)]],
    const device uint32_t* row_ptr [[buffer(2)]],
    const device TC* cols [[buffer(3)]],
    const device TV* vals [[buffer(4)]],
    const device float* scale [[buffer(5)]],
    const device uint32_t* eidx [[buffer(6)]],
    device float* y [[buffer(7)]],
""" + _POS + " {\n" + sw._RESIDUAL_SRC + "}\n"]

    # ---- stacked column-structured residual + optional CSR tail (switch_structured_residual_metal; template order =
    # its template list after the input dtypes MLX derives from x, ccols, cval, rcols, rvals)
    parts += [_section("suc_switch_structured_residual: suc.kernels.suc_switch._COLRES_SRC "
                       "(switch_structured_residual_metal)"), """
template <typename TX, typename TCC, typename TCV, typename TRC, typename TRV, int IN, int OUT, int CMAX, int RQ, int JS,
          int RED, bool HAS_CSR, typename OT>
[[kernel]] void suc_switch_structured_residual(
    const device TX* x [[buffer(0)]],
    const device float* y_in [[buffer(1)]],
    const device uint32_t* eidx [[buffer(2)]],
    const device uint32_t* cptr [[buffer(3)]],
    const device TCC* ccols [[buffer(4)]],
    const device TCV* cval [[buffer(5)]],
    const device float* cscale [[buffer(6)]],
    const device uint32_t* row_ptr [[buffer(7)]],
    const device TRC* rcols [[buffer(8)]],
    const device TRV* rvals [[buffer(9)]],
    const device float* rscale [[buffer(10)]],
    device OT* y [[buffer(11)]],
""" + _POS + " {\n" + sw._COLRES_SRC + "}\n"]
    return parts


# Offset-table prologue of the tcq expert-stack kernels (C++ only), the analogue of _TAB_PROLOGUE: expert e's streams and
# row scales are found through eoff (E, 3) ulong (slot 0 unused: tcq has no codebooks; slot 1 = element offset of the
# words, slot 2 = of the row scales; ~0 in slot 1 = empty slot of a mixed-codec sub-stack: the threadgroup returns).
_TCQ_TAB_PROLOGUE = """
    {
        uint suc_t = threadgroup_position_in_grid.y;
        ulong suc_e = ulong(eidx[suc_t]);
        if (eoff[3 * suc_e + 1] == ~0ul) return;
        words += eoff[3 * suc_e + 1];
        scales += eoff[3 * suc_e + 2];
        x += ulong(suc_t) * ulong(BT * IN);
        y += ulong(suc_t) * ulong(BT * OUT);
    }
"""


def _tcq_sections() -> list[str]:
    """Trellis-coded (tcq) kernels (suc.kernels.tcq_matmul): the "vec" / "mma" bodies for dense tensors, behind the
    tile -> expert prologue (tcq_gather_matmul_metal) and behind the C++-only offset-table prologue. TXX / TSC: the
    dtypes MLX derives from x and the row scales (the C++ host binds the f16 row scales of the file; float(half) is
    exact, so this equals the float32 copy SucLinear holds); cst: float32 [mu_0, c_0, mu_1, c_1] (kernel_consts)."""
    import suc.kernels.tcq_matmul as tq

    parts = [_section("suc.kernels.tcq_matmul._TCQ_HEADER"), tq._TCQ_HEADER]
    head = "template <typename TXX, typename TSC, int L, int V, int KV, int T, int NW, int IN, int OUT, int BT, int CODE,\n"
    tmpl = {"vec": head + "          int SG, int R, typename TO>\n",
            "mma": head + "          int SG, int RT, int NB, typename TT, typename TO>\n"}
    body = {"vec": tq._SRC, "mma": tq._MMA_SRC}
    args = """    const device TXX* x [[buffer(0)]],
    const device uint32_t* words [[buffer(1)]],
    const device TSC* scales [[buffer(2)]],
    const device float* cst [[buffer(3)]],
"""
    for kind in ("vec", "mma"):
        parts += [_section(f"suc_tcq_{kind}: suc.kernels.tcq_matmul.{'_SRC' if kind == 'vec' else '_MMA_SRC'} "
                           f"(tcq_matmul_metal)"),
                  tmpl[kind] + f"[[kernel]] void suc_tcq_{kind}(\n" + args + "    device TO* y [[buffer(4)]],\n" + _POS
                  + " {\n" + body[kind] + "}\n"]
        sw_args = args + "    const device uint32_t* eidx [[buffer(4)]],\n    device TO* y [[buffer(5)]],\n"
        parts += [_section(f"suc_tcq_switch_{kind}: suc.kernels.tcq_matmul._SWITCH_PROLOGUE + the {kind} body "
                           f"(tcq_gather_matmul_metal)"),
                  tmpl[kind] + f"[[kernel]] void suc_tcq_switch_{kind}(\n" + sw_args + _POS + " {\n"
                  + tq._SWITCH_PROLOGUE + body[kind] + "}\n"]
        parts += [_section(f"suc_tcq_switch_{kind}_tab: offset-table prologue (C++ only) + the same body"),
                  tmpl[kind] + f"[[kernel]] void suc_tcq_switch_{kind}_tab(\n" + sw_args
                  + "    const device ulong* eoff [[buffer(6)]],\n" + _POS + " {\n" + _TCQ_TAB_PROLOGUE + body[kind]
                  + "}\n"]
    return parts


