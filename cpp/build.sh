#!/usr/bin/env bash
# Fallback build without CMake (same sources and flags as CMakeLists.txt). Usage:
#   cpp/build.sh [BUILD_DIR]        (default ~/suc-local/cpp-build; keep it on a local disk)
set -euo pipefail
SRC="$(cd "$(dirname "$0")" && pwd)"
OUT="${1:-$HOME/suc-local/cpp-build}"
CXX="${CXX:-c++}"
FLAGS=(-std=c++20 -O2 -ffp-contract=off -Wall -Wextra -I"$SRC/include")
mkdir -p "$OUT/obj"
objs=()
pids=()
for f in "$SRC"/src/*.cpp; do
  o="$OUT/obj/$(basename "${f%.cpp}").o"
  "$CXX" "${FLAGS[@]}" -c "$f" -o "$o" & pids+=($!)
  objs+=("$o")
done
for p in "${pids[@]}"; do wait "$p"; done
pids=()
ar rcs "$OUT/libsuc.a" "${objs[@]}"
"$CXX" "${FLAGS[@]}" "$SRC/tools/suc1_inspect.cpp" "$OUT/libsuc.a" -o "$OUT/suc1-inspect" -pthread & pids+=($!)
"$CXX" "${FLAGS[@]}" "$SRC/tools/suc1_decode.cpp" "$OUT/libsuc.a" -o "$OUT/suc1-decode" -pthread & pids+=($!)
"$CXX" "${FLAGS[@]}" "$SRC/tools/suc_tokenize.cpp" "$OUT/libsuc.a" -o "$OUT/suc-tokenize" -pthread & pids+=($!)
"$CXX" "${FLAGS[@]}" "$SRC/tests/test_main.cpp" "$OUT/libsuc.a" -o "$OUT/suc-tests" -pthread & pids+=($!)
for p in "${pids[@]}"; do wait "$p"; done
"$CXX" "${FLAGS[@]}" "$SRC/tools/suc_sampling_bench.cpp" "$OUT/libsuc.a" -o "$OUT/suc-sampling-bench" -pthread
"$CXX" "${FLAGS[@]}" "$SRC/tests/test_live_prefix.cpp" -o "$OUT/suc-prefix-tests"
# Audit F10: request-helper boundary test under -fsanitize=float-cast-overflow when the compiler supports it.
UBSAN=(-fsanitize=float-cast-overflow -fno-sanitize-recover=float-cast-overflow)
if ! echo 'int main(){return 0;}' | "$CXX" -x c++ "${UBSAN[@]}" - -o "$OUT/obj/ubsan-probe" 2>/dev/null; then UBSAN=(); fi
"$CXX" "${FLAGS[@]}" ${UBSAN[@]+"${UBSAN[@]}"} "$SRC/tests/test_request_params_ubsan.cpp" "$SRC/src/json.cpp" \
  -o "$OUT/suc-request-params-tests"
echo "built: $OUT/{libsuc.a,suc1-inspect,suc1-decode,suc-tokenize,suc-tests,suc-request-params-tests}"

# Metal backend (macOS only): metal-cpp headers, kernels compiled at run time from the embedded
# cpp/metal/suc_kernels.metal (the Command Line Tools have no offline `metal` compiler).
if [[ "$(uname -s)" == Darwin && "${SUC_NO_METAL:-0}" != 1 ]]; then
  MFLAGS=(-isystem "$SRC/third_party/metal-cpp")
  FRAMEWORKS=(-framework Metal -framework Foundation -framework QuartzCore)
  mkdir -p "$OUT/gen"
  gen="$OUT/gen/suc_kernels_msl.cpp"
  {
    printf '// Generated by cpp/build.sh from cpp/metal/suc_kernels.metal, suc_model_kernels.metal, suc_qwen4_kernels.metal, suc_ds4_kernels.metal and suc_glm5_kernels.metal.\n'
    printf 'namespace suc::metal {\nextern const char* const kEmbeddedKernelSource;\n'
    printf 'extern const char* const kEmbeddedModelKernelSource;\n'
    printf 'extern const char* const kEmbeddedQwen4KernelSource;\n'
    printf 'extern const char* const kEmbeddedDs4KernelSource;\n'
    printf 'extern const char* const kEmbeddedGlm5KernelSource;\n'
    printf 'const char* const kEmbeddedKernelSource = R"SUCMSL('
    cat "$SRC/metal/suc_kernels.metal"
    printf ')SUCMSL";\nconst char* const kEmbeddedModelKernelSource = R"SUCMSL('
    cat "$SRC/metal/suc_model_kernels.metal"
    printf ')SUCMSL";\nconst char* const kEmbeddedQwen4KernelSource = R"SUCMSL('
    cat "$SRC/metal/suc_qwen4_kernels.metal"
    printf ')SUCMSL";\nconst char* const kEmbeddedDs4KernelSource = R"SUCMSL('
    cat "$SRC/metal/suc_ds4_kernels.metal"
    printf ')SUCMSL";\nconst char* const kEmbeddedGlm5KernelSource = R"SUCMSL('
    cat "$SRC/metal/suc_glm5_kernels.metal"
    printf ')SUCMSL";\n}  // namespace suc::metal\n'
  } > "$gen.tmp"
  cmp -s "$gen.tmp" "$gen" 2>/dev/null && rm "$gen.tmp" || mv "$gen.tmp" "$gen"
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/metal.cpp" -o "$OUT/obj/metal.o" & pids=($!)
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/model.cpp" -o "$OUT/obj/model.o" & pids+=($!)
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/switch.cpp" -o "$OUT/obj/switch.o" & pids+=($!)
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/qwen4.cpp" -o "$OUT/obj/qwen4.o" & pids+=($!)
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/deepseek_v4.cpp" -o "$OUT/obj/deepseek_v4.o" & pids+=($!)
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/expert_mixed.cpp" -o "$OUT/obj/expert_mixed.o" & pids+=($!)
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/expert_stream.cpp" -o "$OUT/obj/expert_stream.o" & pids+=($!)
  "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" -c "$SRC/src/metal/glm5.cpp" -o "$OUT/obj/glm5.o" & pids+=($!)
  "$CXX" "${FLAGS[@]}" -c "$gen" -o "$OUT/obj/suc_kernels_msl.o" & pids+=($!)
  for p in "${pids[@]}"; do wait "$p"; done
  ar rcs "$OUT/libsuc_metal.a" "$OUT/obj/metal.o" "$OUT/obj/model.o" "$OUT/obj/switch.o" "$OUT/obj/qwen4.o" "$OUT/obj/deepseek_v4.o" "$OUT/obj/expert_mixed.o" "$OUT/obj/expert_stream.o" "$OUT/obj/glm5.o" "$OUT/obj/suc_kernels_msl.o"
  pids=()
  for t in tools/suc1_linear tools/suc_linear_bench tools/suc_mm_bench tools/suc_attention_bench tools/suc1_generate tools/suc1_server tools/suc1_moe tools/suc_expert_bench tests/test_metal tests/test_qwen_checkpoint; do
    exe="$(basename "$t" | tr _ -)"
    [[ "$exe" == test-metal ]] && exe=suc-metal-tests
    [[ "$exe" == test-qwen-checkpoint ]] && exe=suc-qwen-checkpoint-tests
    "$CXX" "${FLAGS[@]}" "${MFLAGS[@]}" "$SRC/$t.cpp" "$OUT/libsuc_metal.a" "$OUT/libsuc.a" "${FRAMEWORKS[@]}" \
      -o "$OUT/$exe" -pthread & pids+=($!)
  done
  for p in "${pids[@]}"; do wait "$p"; done
  echo "built: $OUT/{libsuc_metal.a,suc1-linear,suc-linear-bench,suc-mm-bench,suc1-generate,suc1-server,suc1-moe,suc-expert-bench,suc-metal-tests}"
fi
