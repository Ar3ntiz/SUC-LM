#!/usr/bin/env python3
"""Regenerate the trellis low-tier (tcq) re-encode rows of docs/compression_report.md (§5c) and README.md from result
JSONs (queue: scripts/studio_tcq_frontier.sh; docs/low_tier_codec.md §6).

Per model: the ds4 GGUF reference row, the earlier SUC1 records at the same memory budget, and the tcq re-encode
(newest *_compress_<name>.json: size / KL / top-1 / ΔCE / PPL / tier mix; *_gen_cpp_<g>.json: C++ decode of the
frontier prompt; *_gen_cpp_<g>_short / _long2k.json: batched prefill; *_eval_hard_<x>.json: hard suite). Missing
results print as "—" (not run / failed). Each block between its BEGIN / END markers is replaced (report: after the
§5b block, else before "## 6."; README: before "### Glossary").

    .venv/bin/python scripts/tcq_rows.py [--report docs/compression_report.md] [--readme README.md] [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from size_variants_rows import END as SV_END, RESULTS, fmt, gguf_row, load, newest, suc_row  # noqa: E402

BEGIN = "<!-- tcq-frontier:begin (generated by scripts/tcq_rows.py; do not edit by hand) -->"
END = "<!-- tcq-frontier:end -->"
RBEGIN = "<!-- tcq-summary:begin (generated by scripts/tcq_rows.py; do not edit by hand) -->"
REND = "<!-- tcq-summary:end -->"

# model -> (gguf key, gguf label, [(label, compress name, gen_cpp name, hard eval name, is the tcq row)])
MODELS = {
    "DeepSeek-V4-Flash": ("ds_iq2", "ds4 IQ2_XXS mix (resident)", [
        ("SUC1 V1 native_max (record)", "compress_deepseek_v4_flash_native_max", "deepseek_v4_flash_native_max",
         "eval_hard_ds_v1", False),
        ("SUC1 s97: native / G4 / M3, 96.9 GB", "compress_deepseek_v4_flash_s97", "deepseek_v4_flash_s97", None, False),
        ("SUC1 tcq: native / G4 / M3 / tcq 2+3-bit, 96.9 GB", "compress_deepseek_v4_flash_tcq",
         "deepseek_v4_flash_tcq", "eval_hard_ds_tcq", True),
        ("SUC1 tcq, calibration mix v2 (GSM8K + MATH-train), 96.9 GB", "compress_deepseek_v4_flash_tcq_mathcal",
         "deepseek_v4_flash_tcq_mathcal", "eval_hard20_ds_tcq_mathcal", True),
    ]),
    "GLM-5.3-Flash": ("glm_q2", "ds4 Q2 (SSD streaming)", [
        ("SUC1 base, experts 3.0 bpw, SSD streaming (record)", "compress_glm5.3_flash", "glm5.3_flash_streamed",
         "eval_hard_glm", False),
        ("SUC1 tcq: experts 2.45 bpw incl. tcq 2+3-bit, resident", "compress_glm5.3_flash_tcq", "glm5.3_flash_tcq",
         "eval_hard_glm_tcq", True),
    ]),
}

# runs whose own evaluate-stage KL is on another 16 x 512 protocol (calibration mix v2 changes the validation rows):
# compress name -> (scripts/suc1_cross_kl.py tag of this file, tag of the earlier file); results
# cross_kl_<tag>_on_v1 / _on_v2 (C++ teacher-forced decode vs the v1 resp. v2 run's reference logits)
CROSS = {"compress_deepseek_v4_flash_tcq_mathcal": ("ds_tcq_mathcal", "ds_tcq")}


def _cross_kl(tag: str, proto: str) -> dict:
    return (_newest(f"cross_kl_{tag}_on_{proto}")[1] or {}).get("kl") or {}


def _cross_line(cname: str) -> str | None:
    if cname not in CROSS:
        return None
    new, old = CROSS[cname]
    cell = lambda k: (f"KL {fmt(k.get('kl_mean'), 3)}, top-1 {fmt(k.get('top1_agreement'), 3)}, "
                      f"ΔCE {fmt(k.get('delta_ce'), 3)}") if k else "—"
    return (f"  - same-protocol KL (C++ teacher-forced decode, `scripts/suc1_cross_kl.py`): on the v1 protocol (the "
            f"rows / reference of the earlier tcq run, = the ds4 GGUF rows' protocol) calib v2 file {cell(_cross_kl(new, 'v1'))} "
            f"vs calib v1 file {cell(_cross_kl(old, 'v1'))}; on the v2 protocol (this run's rows / reference) calib v2 "
            f"file {cell(_cross_kl(new, 'v2'))} vs calib v1 file {cell(_cross_kl(old, 'v2'))}. Each file on its own "
            f"protocol is the check of the C++ path against its evaluate stage (the KL column).")


def _newest(name: str) -> tuple[Path | None, dict | None]:
    p = newest(f"*_{name}.json", f"{name}.json")
    return p, load(p)


def _tok_s(g: dict | None) -> float | None:
    run = (g or {}).get("run") or {}
    if run.get("prefill_s") is None or not run.get("prompt_tokens"):
        return None
    return run["prompt_tokens"] / (float(run["prefill_s"]) - float(run.get("prefill_compile_s") or 0.0))


def _hard(name: str | None) -> str:
    if not name:
        return "—"
    _, d = _newest(name)
    if not d:
        return "—"
    (_, s), = d["systems"].items()
    sm = s["summary"]
    return f"{sm['passed']}/{sm['graded']}" + (f" ({sm['errors']} err)" if sm.get("errors") else "")


def _tiers(c: dict | None) -> str:
    """Routed-expert tensors per codec of a compress result (plan.by_codec restricted to expert codecs)."""
    if not c:
        return "—"
    by = (c.get("plan") or {}).get("by_codec") or {}
    short = {"vq_k256_g4": "G4", "additive_m3": "M3", "vq_k256_g2_rot1s_xs": "G2", "mxfp4": "native",
             "tcq_3inst_b2": "tcq2", "tcq_3inst_b3": "tcq3"}
    out = []
    for k, n in sorted(by.items(), key=lambda kv: -kv[1]):
        lab = next((v for pre, v in short.items() if k.startswith(pre)), None)
        if lab:
            out.append(f"{lab} {n:,}")
    return ", ".join(out) or "—"


def report_block() -> str:
    lines = [BEGIN, "", "### 5c. Trellis low tier (tcq) re-encodes", "",
             "docs/low_tier_codec.md §6, owner decision 2026-10-09 (full integration, L=12): the same calibrate / "
             "reference / Fisher and the same candidates as the in-memory variants of §5b (their scores reused: "
             "`plan.candidates_reuse`), plus two routed-expert candidates, tcq 2-bit and 3-bit (3INST, V=2, L=12, "
             "BlockLDLQ with the shared gate/up second moment of each MoE layer and per-expert down moments from the "
             "`hessians` stage, 0.5 % column residual, stack-shared input rotation; scored on 256 rows per expert "
             "tensor with exact bits). Same budget as the variant above it (DeepSeek 96.9 GB total; GLM routed "
             "experts 2.45 bpw, fully resident). KL / top-1 / ΔCE: the 16 × 512 protocol of §5; speed: "
             "`scripts/frontier_measure.py generate` (C++, current build, short frontier prompt, 256 greedy tokens, "
             "resident); hard suite: §7 (30 questions). Queue: `scripts/studio_tcq_frontier.sh`; configs "
             "`experiments/configs/compress_{deepseek_v4_flash,glm5.3_flash}_tcq.yaml`.", "",
             "| Model | system | GB | bpp | resident GB | KL | top-1 | ΔCE | PPL | decode ms/tok | GPU ms/tok | "
             "prefill s | size vs GGUF | result |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    extra = []
    for model, (key, glabel, rows) in MODELS.items():
        rec = load(newest(f"*_{rows[0][1]}.json", f"{rows[0][1]}.json")) or {}
        grow, ggb = gguf_row(key, glabel, (rec.get("size") or {}).get("parameter_count"))
        lines.append(grow.replace("| |", f"| {model} |", 1))
        for label, cname, gname, hard, is_tcq in rows:
            lines.append(suc_row(label, cname, gname, ggb, is_tcq))
            if is_tcq:
                _, c = _newest(cname)
                sh, lg = _newest(f"gen_cpp_{gname}_short")[1], _newest(f"gen_cpp_{gname}_long2k")[1]
                extra.append(f"- {model}, {label}: routed-expert tensors {_tiers(c)}; prefill {fmt(_tok_s(sh), 1)} tok/s "
                             f"(short) / {fmt(_tok_s(lg), 1)} tok/s (2048 tokens); hard suite {_hard(hard)}.")
                if _cross_line(cname):
                    extra.append(_cross_line(cname) + " The KL column of this row is on the v2 protocol "
                                 "(other validation rows than the rows above it).")
    lines += [""] + extra + ["", END]
    return "\n".join(lines)


def readme_block() -> str:
    lines = [RBEGIN, "", "**Trellis low tier (tcq) re-encodes** (docs/low_tier_codec.md, report §5c; same 16 × 512 KL "
             "protocol and C++ speed protocol as the table above; the previous SUC1 file at the same memory budget "
             "and the ds4 GGUF for reference):", "",
             "| Model | SUC1 tcq file (bpp) | KL (tcq / previous SUC1) | top-1 | decode tok/s | prefill tok/s, short / 2048 "
             "| hard suite | ds4 GGUF (KL) |", "|---|---|---|---|---|---|---|---|"]
    notes = []
    for model, (key, glabel, rows), j in ((m, v, j) for m, v in MODELS.items() for j, r in enumerate(v[2]) if r[4]):
        prev, tcq = rows[j - 1], rows[j]
        _, c = _newest(tcq[1])
        _, cp = _newest(prev[1])
        g = _newest(f"gen_cpp_{tcq[2]}")[1]
        sh, lg = _newest(f"gen_cpp_{tcq[2]}_short")[1], _newest(f"gen_cpp_{tcq[2]}_long2k")[1]
        size = (c or {}).get("size") or {}
        kl = ((c or {}).get("quality") or {}).get("kl") or {}
        klp = ((cp or {}).get("quality") or {}).get("kl") or {}
        mark = ""
        if tcq[1] in CROSS:      # own KL is on another protocol: both files on the v1 protocol (C++), marked †
            kl, klp = _cross_kl(CROSS[tcq[1]][0], "v1"), _cross_kl(CROSS[tcq[1]][1], "v1")
            mark = "†"
            model = f"{model} (calib mix v2)"
            notes.append("† calibration mix v2 changes the validation rows: both KL values on the v1 rows / reference, "
                         "C++ teacher-forced decode (`scripts/suc1_cross_kl.py`; report §5c).")
        dec = ((g or {}).get("summary") or {}).get("decode_tok_s_median")
        qs = [p for p in sorted(RESULTS.glob(f"*_gguf_quality_{key}.json")) if (load(p).get("kl") or {}).get("kl_mean")]
        gk = ((load(qs[-1]) if qs else {}).get("kl") or {}).get("kl_mean")
        gb = size.get("file_bytes") / 1e9 if size.get("file_bytes") else None
        lines.append(f"| {model} | {fmt(gb)} GB ({fmt(size.get('bpp'), 3)}) | {fmt(kl.get('kl_mean'), 3)} / "
                     f"{fmt(klp.get('kl_mean'), 3)}{mark} ({prev[0].split(':')[0].split(',')[0]}) | {fmt(kl.get('top1_agreement'), 3)} | "
                     f"{fmt(dec, 1)} | {fmt(_tok_s(sh), 1)} / {fmt(_tok_s(lg), 1)} | {_hard(tcq[3])} | "
                     f"{glabel.split(' (')[0]} ({fmt(gk, 3)}) |")
    lines += [""] + notes + ([""] if notes else []) + [REND]
    return "\n".join(lines)


def _replace(s: str, begin: str, end: str, block: str, after: str | None, before: str) -> str:
    if begin in s and end in s:
        return s[:s.index(begin)] + block + s[s.index(end) + len(end):]
    if after is not None and after in s:
        i = s.index(after) + len(after)
        return s[:i] + "\n\n" + block + s[i:]
    i = s.index(before)
    return s[:i] + block + "\n\n" + s[i:]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default=str(ROOT / "docs" / "compression_report.md"))
    ap.add_argument("--readme", default=None, help="also write the summary block into this file (the README no longer carries it)")
    ap.add_argument("--check", action="store_true", help="print the blocks, do not write")
    a = ap.parse_args()
    rb, mb = report_block(), readme_block()
    if a.check:
        print(rb + "\n\n" + mb)
        return
    p = Path(a.report)
    p.write_text(_replace(p.read_text(), BEGIN, END, rb, SV_END, "\n## 6."))
    print(f"{p}: tcq block updated")
    if a.readme:
        r = Path(a.readme)
        r.write_text(_replace(r.read_text(), RBEGIN, REND, mb, None, "### Glossary"))
        print(f"{r}: tcq summary updated")


if __name__ == "__main__":
    main()
