#!/usr/bin/env python3
"""Regenerate the "size / speed variants" block of docs/compression_report.md (§5b) from result JSONs.

Owner decision 2026-10-08: the hard suite showed the ds4 GGUFs about as reliable as SUC1, so SUC's KL headroom is spent
on file size and decode speed. Per model: the ds4 GGUF reference row (newest gguf_quality / gguf_perf of its key),
the earlier SUC1 record and the new variants (newest *_compress_<config name>.json for size / KL / top-1 / ΔCE / PPL,
newest *_gen_cpp_<name>.json for the C++ short-prompt decode: scripts/frontier_measure.py generate, 256 greedy tokens).
Missing results print as "—" (not run / failed). The block between BEGIN / END is replaced (inserted before "## 6."
when absent).

    .venv/bin/python scripts/size_variants_rows.py [--report docs/compression_report.md] [--check]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "experiments" / "results"
BEGIN = "<!-- size-variants:begin (generated by scripts/size_variants_rows.py; do not edit by hand) -->"
END = "<!-- size-variants:end -->"

# model -> (gguf key, gguf label, [(row label, compress name, gen_cpp name, note)])
MODELS = {
    "DeepSeek-V4-Flash": ("ds_iq2", "ds4 IQ2_XXS mix (resident)", [
        ("SUC1 V1 native_max (record)", "compress_deepseek_v4_flash_native_max", "deepseek_v4_flash_native_max", ""),
        ("SUC1 s97: native / G4 / M3, 96.9 GB budget", "compress_deepseek_v4_flash_s97", "deepseek_v4_flash_s97", "new"),
        ("SUC1 s94: native / G4 / M3, 94.0 GB budget", "compress_deepseek_v4_flash_s94", "deepseek_v4_flash_s94", "new"),
    ]),
    "GLM-5.3-Flash": ("glm_q2", "ds4 Q2 (SSD streaming)", [
        ("SUC1 base, experts 3.0 bpw, SSD streaming (record)", "compress_glm5.3_flash", "glm5.3_flash_streamed", ""),
        ("SUC1 r245: experts 2.45 bpw, resident", "compress_glm5.3_flash_r245", "glm5.3_flash_r245", "new"),
        ("SUC1 r235: experts 2.35 bpw, resident", "compress_glm5.3_flash_r235", "glm5.3_flash_r235", "new"),
    ]),
    "Qwen3.8-Flash-Next": ("q38_q4", "ds4 Q4 (resident, BF16 n-gram rows from disk)", [
        ("SUC1 side8 (ngram4, record)", "compress_qwen3.8_flash_next_side8", "qwen3.8_flash_next_side8_ngram4", ""),
        ("SUC1 g94: Fisher greedy, 94.0 GB budget", "compress_qwen3.8_flash_next_g94", "qwen3.8_flash_next_g94", "new"),
        ("SUC1 g91: Fisher greedy, 91.0 GB budget", "compress_qwen3.8_flash_next_g91", "qwen3.8_flash_next_g91", "new"),
    ]),
}


def newest(pattern: str, exact_suffix: str | None = None) -> Path | None:
    ps = sorted(RESULTS.glob(pattern))
    if exact_suffix is not None:
        ps = [p for p in ps if p.name.split("_", 1)[1] == exact_suffix]
    return ps[-1] if ps else None


def load(p: Path | None) -> dict | None:
    return json.loads(p.read_text()) if p else None


def fmt(x, nd=2):
    return "—" if x is None else f"{x:,.{nd}f}"


def gguf_row(key: str, label: str, params: int | None) -> tuple[str, float | None]:
    """bpp = whole GGUF file bits / the model's parameter count of the SUC1 record (as §5)."""
    qs = [p for p in sorted(RESULTS.glob(f"*_gguf_quality_{key}.json")) if (load(p).get("kl") or {}).get("kl_mean")]
    q = load(qs[-1]) if qs else None
    pf = load(newest(f"*_gguf_perf_{key}.json"))
    kl = (q or {}).get("kl") or {}
    gb = ((q or {}).get("gguf") or {}).get("file_bytes")
    bpp = gb * 8 / params if gb and params else None
    sp = ((pf or {}).get("summary") or {}).get("short_prompt") or {}
    src = ", ".join(f"R:`{p.stem}`" for p in (qs[-1] if qs else None, newest(f"*_gguf_perf_{key}.json")) if p)
    row = (f"| | {label} | {fmt(gb / 1e9 if gb else None)} | {fmt(bpp, 3)} | — | **{fmt(kl.get('kl_mean'), 4)}** | "
           f"{fmt(kl.get('top1_agreement'), 3)} | {fmt(kl.get('delta_ce'), 4)} | — | {fmt(sp.get('decode_ms_median'))} | "
           f"— | {fmt(sp.get('prefill_s'))} | — | {src} |")
    return row, (gb / 1e9 if gb else None)


def suc_row(label: str, cname: str, gname: str, gguf_gb: float | None, new: bool) -> str:
    cp = newest(f"*_{cname}.json", f"{cname}.json")
    c = load(cp)
    gp = newest(f"*_gen_cpp_{gname}.json", f"gen_cpp_{gname}.json")
    g = load(gp)
    size, kl, ppl = (c or {}).get("size") or {}, ((c or {}).get("quality") or {}).get("kl") or {}, \
        ((c or {}).get("quality") or {}).get("perplexity") or {}
    run = (g or {}).get("run") or {}
    mem = run.get("memory") or {}
    gb = size.get("file_bytes") / 1e9 if size.get("file_bytes") else None
    res = (mem.get("mapped_file", 0) + mem.get("phys_footprint", 0)) / 1e9 if mem.get("mapped_file") else None
    hit = ((g or {}).get("summary") or {}).get("hit_rate")
    dec = ((g or {}).get("summary") or {}).get("decode_ms_median")
    dsize = f"{(gb - gguf_gb) / gguf_gb * 100:+.1f} %" if gb and gguf_gb else "—"
    src = ", ".join(f"R:`{p.stem}`" for p in (cp, gp) if p) or "not run yet"
    name = f"**{label}**" if new else label
    pre = f"{fmt(run.get('prefill_s'))} ({run.get('prompt_tokens')} tok)" if run.get("prefill_s") is not None else "—"
    return (f"| | {name} | {fmt(gb)} | {fmt(size.get('bpp'), 3)} | {fmt(res)}"
            f"{' (hit ' + fmt(hit, 3) + ')' if hit else ''} | {fmt(kl.get('kl_mean'), 4)} | "
            f"{fmt(kl.get('top1_agreement'), 3)} | {fmt(kl.get('delta_ce'), 4)} | {fmt(ppl.get('ppl'), 3)} | "
            f"{fmt(dec)} | {fmt(run.get('decode_gpu_ms_per_token_median'))} | {pre} | {dsize} | {src} |")


def block() -> str:
    lines = [BEGIN, "", "### 5b. Size / speed variants: SUC1 at the GGUF quality level", "",
             "Owner decision 2026-10-08 (after the hard suite: the ds4 GGUFs answer about as well as SUC1): spend SUC's "
             "KL headroom on file size and decode speed. Re-plans of the existing calibrate / reference / candidates "
             "artifacts (DeepSeek, GLM: `plan.allocation` overrides, no new Fisher pass; Qwen3.8: the first "
             "Fisher-greedy run of the model, both budgets from one candidates stage). KL / top-1 / ΔCE: the 16 × 512 "
             "protocol of §5 (evaluate stage of the compress run; GGUF: `scripts/gguf_compare.py`). Speed: "
             "`scripts/frontier_measure.py generate` (current build, short prompt, 256 greedy tokens, single run, "
             "resident unless a hit rate is shown); GGUF: the §5 short-prompt run. Resident = mapped file + process "
             "footprint. Queue: `scripts/studio_size_variants.sh`; configs `experiments/configs/compress_*_{s97,s94,"
             "r245,r235,g94,g91}.yaml` (headers: plan-only predictions).", "",
             "| Model | system | GB | bpp | resident GB | KL | top-1 | ΔCE | PPL | decode ms/tok | GPU ms/tok | "
             "prefill s | size vs GGUF | result |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for model, (key, glabel, rows) in MODELS.items():
        rec = load(newest(f"*_{rows[0][1]}.json", f"{rows[0][1]}.json")) or {}
        grow, ggb = gguf_row(key, glabel, ((rec.get("size") or {}).get("parameter_count")))
        lines.append(grow.replace("| |", f"| {model} |", 1))
        for label, cname, gname, note in rows:
            lines.append(suc_row(label, cname, gname, ggb, note == "new"))
    lines += ["", "Qwen3.8: the GGUF file keeps the BF16 n-gram table (102.4 GB) out of its weight mapping (§5 note 10; "
              "resident weights 74.8 GB), so its file size is not the comparable quantity there: compare resident "
              "bytes and decode speed.", "", END]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default=str(ROOT / "docs" / "compression_report.md"))
    ap.add_argument("--check", action="store_true", help="print the block, do not write")
    a = ap.parse_args()
    b = block()
    if a.check:
        print(b)
        return
    p = Path(a.report)
    s = p.read_text()
    if BEGIN in s and END in s:
        s = s[:s.index(BEGIN)] + b + s[s.index(END) + len(END):]
    else:
        i = s.index("\n## 6.")
        s = s[:i] + "\n" + b + "\n" + s[i:]
    p.write_text(s)
    print(f"{p}: size-variants block updated")


if __name__ == "__main__":
    main()
