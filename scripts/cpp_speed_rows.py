"""Regenerate the C++ speed tables of docs/compression_report.md (§1b decode, §1c prefill / TTFT) and the "SUC prefill
tok/s" column of the README summary table from result JSONs.

§1b: for each model the newest `*_gen_cpp_<name>.json` in experiments/results (scripts/frontier_measure.py generate:
suc1-generate, batch 1, greedy) is the current row; the next older result of the same name, if any, is the previous
record. §1c: the newest `*_gen_cpp_<name>_{short,long2k,long2k_token}.json` (scripts/studio_prefill_measure.sh,
scripts/studio_fast_prefill_queue.sh) and, for every model that has one, the newest
`*_prefill_batch_vs_token_<name>.json` (scripts/prefill_batch_vs_token.py). Each
block between its BEGIN / END markers is replaced (inserted before "## 2." when absent); README cells are rewritten in
place (rows matched by their model label).

    .venv/bin/python scripts/cpp_speed_rows.py [--report docs/compression_report.md] [--readme README.md] [--check]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "experiments" / "results"
BEGIN = "<!-- cpp-decode-current:begin (generated by scripts/cpp_speed_rows.py; do not edit by hand) -->"
END = "<!-- cpp-decode-current:end -->"

# (row label, result name suffix after "gen_cpp_")
MODELS = [
    ("Qwen3-8B (final)", "qwen3_8b_final"),
    ("Qwen3-30B-A3B (final, uniform)", "qwen3_30b_a3b_final"),
    ("Qwen3.8-Flash-Next side8 (ngram4)", "qwen3.8_flash_next_side8_ngram4"),
    ("Qwen3.8-Flash-Next iso (ngram4)", "qwen3.8_flash_next_iso_ngram4"),
    ("DeepSeek-V4-Flash V1 (native_max, in memory)", "deepseek_v4_flash_native_max"),
    ("DeepSeek-V4-Flash V3 (native_stream, SSD experts)", "deepseek_v4_flash_native_stream"),
    ("GLM-5.3-Flash (SSD experts)", "glm5.3_flash_streamed"),
    ("DeepSeek-V4-Flash tcq (in memory)", "deepseek_v4_flash_tcq"),
    ("GLM-5.3-Flash tcq (in memory)", "glm5.3_flash_tcq"),
    ("DeepSeek-V4-Flash tcq, calib mix v2 (in memory)", "deepseek_v4_flash_tcq_mathcal"),
]


def results_for(name: str) -> list[Path]:
    # exact name: "<ts>_gen_cpp_<name>.json" (not the _prefetch / _resset variants)
    return sorted(p for p in RESULTS.glob(f"*_gen_cpp_{name}.json") if p.name.split("_", 1)[1] == f"gen_cpp_{name}.json")


def fmt(x, nd=2):
    return "—" if x is None else f"{x:,.{nd}f}"


def row(label: str, name: str) -> str:
    files = results_for(name)
    if not files:
        return f"| {label} | — | — | — | — | — | — | — | not measured |"
    cur = json.loads(files[-1].read_text())
    r, meta = cur["run"], cur["metadata"]
    dec = r.get("decode_ms_per_token_median")
    gpu = r.get("decode_gpu_ms_per_token_median")
    hit = (r.get("expert_streaming") or {}).get("hit_rate")
    pre = r.get("prefill_s")
    ptok = r.get("prompt_tokens")
    prev, delta = "—", "—"
    if len(files) > 1:
        p = json.loads(files[-2].read_text())["run"].get("decode_ms_per_token_median")
        if p and dec:
            prev = f"{p:.2f} (R:`{files[-2].stem}`)"
            delta = f"{(dec / p - 1) * 100:+.1f} %"
    return (f"| {label} | {fmt(dec)} | {fmt(1000 / dec, 1) if dec else '—'} | {fmt(gpu)} | "
            f"{fmt(pre)} ({ptok} tok) | {fmt(hit, 3) if hit is not None else '—'} | {prev} | {delta} | "
            f"R:`{files[-1].stem}` ({meta.get('git_commit', '')[:7]}) |")


PBEGIN = "<!-- cpp-prefill-current:begin (generated by scripts/cpp_speed_rows.py; do not edit by hand) -->"
PEND = "<!-- cpp-prefill-current:end -->"
PMODELS = MODELS + [("Qwen3.8-27B side8 (dense)", "qwen3.8_27b_side8"), ("Qwen3.8-27B base (dense)", "qwen3.8_27b_base")]
# README summary-table row label (first cell) -> prefill result name
README_PREFILL = {
    "Qwen3-8B": "qwen3_8b_final",
    "Qwen3.8-27B (side8) ⁴": "qwen3.8_27b_side8",
    "Qwen3-30B-A3B (uniform)": "qwen3_30b_a3b_final",
    "Qwen3.8-Flash-Next (side8, ngram4)": "qwen3.8_flash_next_side8_ngram4",
    "DeepSeek-V4-Flash V1 (native_max, in memory)": "deepseek_v4_flash_native_max",
    "DeepSeek-V4-Flash V3 (native_stream, SSD experts)": "deepseek_v4_flash_native_stream",
    "GLM-5.3-Flash (SSD experts)": "glm5.3_flash_streamed",
}


def _newest(name: str, kind: str = "gen_cpp") -> dict | None:
    files = sorted(p for p in RESULTS.glob(f"*_{kind}_{name}.json") if p.name.split("_", 1)[1] == f"{kind}_{name}.json")
    return json.loads(files[-1].read_text()) | {"_stem": files[-1].stem} if files else None


def _prefill(run: dict) -> tuple[float | None, int | None]:
    """(prefill seconds without the pipeline compiles it triggered, prompt tokens)."""
    if not run or run.get("prefill_s") is None:
        return None, None
    return float(run["prefill_s"]) - float(run.get("prefill_compile_s") or 0.0), run.get("prompt_tokens")


def prow(label: str, name: str) -> str | None:
    sh, lg, tk = (_newest(f"{name}_{k}") for k in ("short", "long2k", "long2k_token"))
    if not (sh or lg):
        return None
    cells = []
    for rec in (sh, lg):
        run = (rec or {}).get("run") or {}
        pf, n = _prefill(run)
        dec = run.get("decode_ms_per_token_median")
        cells += [f"{n}" if n else "—", fmt(n / pf, 1) if pf else "—",
                  fmt(pf + (dec or 0) / 1000, 2) if pf else "—", fmt(dec)]
    trun = (tk or {}).get("run") or {}
    tpf, tn = _prefill(trun)
    lrun = (lg or {}).get("run") or {}
    lpf, ln = _prefill(lrun)
    base = fmt(tn / tpf, 1) if tpf else "—"
    speed = f"{tpf / lpf:.1f}x" if tpf and lpf else "—"
    same = "—"
    if lrun.get("prefill_logits_sha256") and trun.get("prefill_logits_sha256"):
        ok = (lrun["prefill_logits_sha256"], lrun.get("prefill_streams_sha256")) == \
             (trun["prefill_logits_sha256"], trun.get("prefill_streams_sha256"))
        same = "yes" if ok else "**no**"
    src = ", ".join(f"R:`{r['_stem']}`" for r in (sh, lg, tk) if r)
    commit = ((lg or sh)["metadata"].get("git_commit") or "")[:7]
    return f"| {label} | " + " | ".join(cells) + f" | {base} | {speed} | {same} | {src} ({commit}) |"


def longrow(label: str, name: str) -> str | None:
    """8k / 32k-token prompts (scripts/studio_prefill_final.sh): prefill tok/s, TTFT, decode after the prompt."""
    recs = [_newest(f"{name}_{k}") for k in ("long2k", "long8k", "long32k")]
    if not (recs[1] or recs[2]):
        return None
    cells = []
    for rec in recs:
        run = (rec or {}).get("run") or {}
        pf, n = _prefill(run)
        dec = run.get("decode_ms_per_token_median")
        cells += [fmt(n / pf, 1) if pf else "—", fmt(pf + (dec or 0) / 1000, 2) if pf else "—", fmt(dec)]
    src = ", ".join(f"R:`{r['_stem']}`" for r in recs[1:] if r)
    commit = ((recs[1] or recs[2])["metadata"].get("git_commit") or "")[:7]
    return f"| {label} | " + " | ".join(cells) + f" | {src} ({commit}) |"


def kvrow(label: str, name: str) -> str | None:
    rec = _newest(name, "prefill_batch_vs_token")
    if not rec:
        return None
    pp, cp, lt, fr = (rec.get(k) or {} for k in ("prompt_positions", "continuation_positions", "last_prompt_token",
                                                  "free_running"))
    def kl(d):
        return f"{d['kl_mean']:.2e} / {d['kl_max']:.2e}" if d else "—"
    def t1(d):
        return f"{d['top1_agreement']:.4f} ({d['top1_mismatches']})" if d else "—"
    fd = fr.get("first_divergence_step")
    return (f"| {label} | {rec.get('prompt_tokens')} | {kl(pp)} | {t1(pp)} | {kl(cp)} | {t1(cp)} | "
            f"{lt.get('kl_mean', float('nan')):.2e} | {lt.get('top1_agreement', float('nan')):.0f} | "
            f"{'identical' if fd is None else fd} ({fr.get('tokens')}) | R:`{rec['_stem']}` |")


