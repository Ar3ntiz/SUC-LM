def readme_prefill(text: str) -> str:
    """Rewrites the "SUC prefill tok/s, short / 2048 tok" cells of the README summary table (column 4) from the
    newest §1c records; a suffix after the two numbers (e.g. the `suc perf` reference in parentheses) is kept, bold
    marks the short-prompt value when it beats the ds4 short-prompt prefill (column 8)."""
    out = []
    for ln in text.split("\n"):
        cells = ln.split("|")
        label = cells[1].strip() if len(cells) > 11 else ""
        name = README_PREFILL.get(label)
        if name:
            vals = []
            for k in ("short", "long2k"):
                pf, n = _prefill(((_newest(f"{name}_{k}") or {}).get("run")) or {})
                vals.append(n / pf if pf else None)
            if vals[0] or vals[1]:
                old = cells[4].strip()
                tail = old.split(" / ", 1)[1] if " / " in old else ""
                tail = tail.split(" ", 1)[1] if " " in tail else ""
                try:
                    ds4 = float(cells[8].strip().replace(",", "").strip("*"))
                except ValueError:
                    ds4 = None
                short = fmt(vals[0], 1) if vals[0] else "—"
                if vals[0] and ds4 and vals[0] > ds4:
                    short = f"**{short}**"
                cells[4] = f" {short} / {fmt(vals[1], 1) if vals[1] else '—'}{(' ' + tail) if tail else ''} "
                ln = "|".join(cells)
        out.append(ln)
    return "\n".join(out)


def block() -> str:
    lines = [
        BEGIN,
        "### 1b. C++ decode, current build",
        "",
        "`scripts/frontier_measure.py generate`: `suc1-generate` with its defaults at the commit shown, batch 1, greedy,",
        "the frontier prompt (prefill column: its tokens; GLM with a trailing comma), 256 tokens, single run, decode =",
        "median of steps 2…256; streamed rows with the",
        "`--expert-budget` / `--hot-experts auto` of their earlier records. The §1 decode column is taken from these rows",
        "(Qwen3.8-27B: the §1c short row).",
        "",
        "| Model | decode ms/tok | tok/s | GPU ms/tok | prefill s | expert hit rate | previous record ms/tok | Δ | result (commit) |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    lines += [row(label, name) for label, name in MODELS]
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--report", default=str(ROOT / "docs" / "compression_report.md"))
    ap.add_argument("--readme", default=None, help="also rewrite the prefill cells of this file's old summary table")
    ap.add_argument("--check", action="store_true", help="print the block, do not write")
    a = ap.parse_args()
    b = block()
    if a.check:
        print(b)
        print(pblock())
        return 0
    path = Path(a.report)
    text = path.read_text()
    for beg, end, blk in ((BEGIN, END, b), (PBEGIN, PEND, pblock())):
        if beg in text and end in text:
            i, j = text.index(beg), text.index(end) + len(end)
            text = text[:i] + blk + text[j:]
        else:
            anchor = "## 2. The original models' own speed"
            if anchor not in text:
                raise SystemExit(f"{path}: neither the markers nor '{anchor}' found")
            text = text.replace(anchor, blk + "\n\n" + anchor, 1)
    path.write_text(text)
    rp = Path(a.readme) if a.readme else None
    if rp and rp.exists():
        rp.write_text(readme_prefill(rp.read_text()))
    print(b)
    print(pblock())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
